package javaBasicTOadvance.sheet1;

public class Sheet1Que5 {
    public static void main(String[] args) {
        int a = 13;
        int b = 14;
        System.out.println("before swapping :"+a + ":"+b);

        int x = a;
        a = b;
        b = x;
        System.out.println("after swapping: "+a +":"+b);
    }
}
